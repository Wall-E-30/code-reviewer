"""
action/reactions.py

Subsequent-run maintainer reaction polling module for Aion Code Reviewer.
Inspects previously posted Aion review comments on pull requests to track:
- Positive reactions (+1, heart, rocket)
- Negative reactions (-1, confused)
- Resolved comment threads and subsequent code amendments
Provides flywheel feedback for RL reward modeling without requiring a hosted webhook server.
"""

from __future__ import annotations

import logging
import re
from typing import Any, Dict, List, Optional
from pydantic import BaseModel, ConfigDict, Field

from action.github_client import GitHubClient

logger = logging.getLogger(__name__)

AION_SIGNATURES = [
    "Aion Finding:",
    "Reported by [Aion Code Reviewer]",
    "Aion Code Reviewer",
]

RESOLVED_KEYWORDS_RE = re.compile(
    r"\b(fixed|done|resolved|applied|merged|addressed|updated)\b",
    re.IGNORECASE,
)


class ReactionSummary(BaseModel):
    """Aggregated maintainer reaction metrics for a pull request."""

    total_tracked: int = 0
    resolved_count: int = 0
    dismissed_count: int = 0
    positive_reactions: int = 0
    negative_reactions: int = 0
    neutral_reactions: int = 0
    reaction_details: List[Dict[str, Any]] = Field(default_factory=list)

    model_config = ConfigDict(populate_by_name=True, extra="ignore")

    def to_dict(self) -> Dict[str, Any]:
        """Convert ReactionSummary to standard dictionary."""
        return self.model_dump()


def is_aion_comment(comment_body: str) -> bool:
    """Determine whether a comment was generated by Aion Code Reviewer."""
    if not comment_body:
        return False
    return any(sig in comment_body for sig in AION_SIGNATURES)


def poll_previous_reactions(
    github_client: GitHubClient,
    repo: str,
    pr_number: int,
    modified_lines_map: Optional[Dict[str, set[int]]] = None,
) -> ReactionSummary:
    """
    Poll and analyze reactions and resolution states of previous Aion comments on the PR.

    Parameters:
        github_client: Configured GitHub REST API client
        repo: Repository identifier ('owner/repo')
        pr_number: Pull request number
        modified_lines_map: Optional mapping of file_path -> set of currently modified line numbers

    Returns:
        ReactionSummary aggregating positive/negative reactions and resolved status.
    """
    raw_comments = github_client.get_existing_review_comments(repo, pr_number)
    if not raw_comments:
        return ReactionSummary()

    # Filter to comments posted by Aion
    aion_comments: List[Dict[str, Any]] = []
    reply_comments_by_reply_id: Dict[int, List[Dict[str, Any]]] = {}

    for c in raw_comments:
        body = c.get("body", "")
        reply_to = c.get("in_reply_to_id")
        if reply_to is not None:
            reply_comments_by_reply_id.setdefault(reply_to, []).append(c)

        if is_aion_comment(body):
            aion_comments.append(c)

    summary = ReactionSummary(total_tracked=len(aion_comments))

    for ac in aion_comments:
        comment_id = ac.get("id", 0)
        file_path = ac.get("path", "")
        line_no = ac.get("line")
        body = ac.get("body", "")

        # Extract category and rule_id from Aion comment body
        category = "bug"
        if "Security Vulnerability" in body:
            category = "security"
        elif "Logic Bug" in body:
            category = "bug"
        elif "Performance Issue" in body:
            category = "performance"
        elif "Code Quality Finding" in body or "Stylistic Note" in body:
            category = "style"

        rule_match = re.search(r"Aion Finding: [^(`\n]*\(`([^`]+)`\)", body)
        rule_id = rule_match.group(1) if rule_match else None

        # Parse reactions
        reactions = ac.get("reactions", {})
        pos = (
            reactions.get("+1", 0)
            + reactions.get("heart", 0)
            + reactions.get("rocket", 0)
        )
        neg = reactions.get("-1", 0) + reactions.get("confused", 0)
        neutral = reactions.get("eyes", 0) + reactions.get("laugh", 0)

        summary.positive_reactions += pos
        summary.negative_reactions += neg
        summary.neutral_reactions += neutral

        # Check resolution status
        is_resolved = False
        is_dismissed = False

        # 1. Check if user replied with resolution keywords
        replies = reply_comments_by_reply_id.get(comment_id, [])
        for r in replies:
            reply_text = r.get("body", "")
            if RESOLVED_KEYWORDS_RE.search(reply_text):
                is_resolved = True
                break
            if "wontfix" in reply_text.lower() or "false positive" in reply_text.lower():
                is_dismissed = True
                break

        # 2. Check if subsequent commits touched the referenced line
        if not is_resolved and modified_lines_map and file_path and line_no:
            active_lines = modified_lines_map.get(file_path, set())
            if line_no in active_lines:
                # Line was amended in subsequent commits!
                is_resolved = True

        if is_resolved:
            summary.resolved_count += 1
        elif is_dismissed:
            summary.dismissed_count += 1

        summary.reaction_details.append(
            {
                "comment_id": comment_id,
                "file_path": file_path,
                "line": line_no,
                "category": category,
                "rule_id": rule_id,
                "body": body,
                "positive": pos,
                "negative": neg,
                "resolved": is_resolved,
                "dismissed": is_dismissed,
            }
        )

    logger.debug(
        "Reaction polling for %s PR #%d: %d tracked, +%d/-%d, %d resolved.",
        repo,
        pr_number,
        summary.total_tracked,
        summary.positive_reactions,
        summary.negative_reactions,
        summary.resolved_count,
    )
    return summary

