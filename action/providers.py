logger = logging.getLogger(__name__)

SYSTEM_PROMPT = """You are Aion, an expert high-precision code review intelligence system.
Your mission is to detect real, actionable defects: logic bugs, security vulnerabilities,
fatal crashes, off-by-one errors, or severe performance degradations in pull request diffs.

CRITICAL INSTRUCTIONS:
1. FOCUS EXCLUSIVELY on real defects. Do not comment on formatting, variable naming preferences,
   subjective stylistic choices, or docstrings.
2. Every finding MUST include a concrete, 1-click replacement in the "suggestion" field.
3. Output MUST be a valid JSON array of objects conforming to this exact schema:
[
  {
    "line_number": <int: 1-based line number in the new/modified file>,
    "category": <"bug" | "security" | "performance" | "style">,
    "severity": <"critical" | "major" | "minor">,
    "comment": "<concise explanation of the defect and why it fails>",
    "suggestion": "<replacement code line(s) that fix the issue>",
    "confidence": <float: 0.0 to 1.0>,
    "rule_id": "<short-kebab-rule-identifier>"
  }
]
If there are no concrete defects, return an empty JSON array: []
Return ONLY the JSON array. Do not include markdown code fence formatting outside the JSON array.
"""


class CandidateComment(BaseModel):
    """A candidate review comment generated by a provider or static linter."""

    file_path: str
    line_number: int
    category: str = "bug"
    severity: str = "major"
    comment: str
    suggestion: Optional[str] = None
    confidence: float = 1.0
    rule_id: Optional[str] = None

    model_config = ConfigDict(populate_by_name=True, extra="ignore")

    def __init__(
        self,
        file_path: str = "",
        line_number: int = 1,
        category: str = "bug",
        severity: str = "major",
        comment: str = "",
        suggestion: Optional[str] = None,
        confidence: float = 1.0,
        rule_id: Optional[str] = None,
        **data: Any,
    ) -> None:
        if file_path or "file_path" in data:
            data.setdefault("file_path", file_path)
        if line_number is not None or "line_number" in data:
            data.setdefault("line_number", line_number)
        if category or "category" in data:
            data.setdefault("category", category)
        if severity or "severity" in data:
            data.setdefault("severity", severity)
        if comment or "comment" in data:
            data.setdefault("comment", comment)
        if suggestion is not None or "suggestion" in data:
            data.setdefault("suggestion", suggestion)
        if confidence is not None or "confidence" in data:
            data.setdefault("confidence", confidence)
        if rule_id is not None or "rule_id" in data:
            data.setdefault("rule_id", rule_id)
        super().__init__(**data)

    def to_dict(self) -> Dict[str, Any]:
        """Convert CandidateComment to standard Python dictionary."""
        return self.model_dump()


class BaseReviewProvider(ABC):
    """Base interface for all code review inference providers."""

    @abstractmethod
    def generate_review(
        self,
        file_path: str,
        diff_hunk: str,
        context: str,
        language: str,
        convention_context: Optional[str] = None,
    ) -> List[CandidateComment]:
        """
        Generate candidate code review comments for a diff hunk with surrounding context.

        Parameters:
            file_path: Path of the modified file
            diff_hunk: Unified diff hunk content
            context: Enclosing scope and context window
            language: Target programming language (e.g. 'python', 'typescript')
            convention_context: Optional repository conventions and team preferences

        Returns:
            List of CandidateComment objects.
        """
        pass


class MockReviewProvider(BaseReviewProvider):
    """
    Deterministic offline reviewer for hermetic CI testing and validation.

    Allows injection of canned comments or provides deterministic defect detection
    based on diff hunk contents.
    """

    def __init__(
        self,
        canned_comments: Optional[List[CandidateComment]] = None,
        default_confidence: float = 0.85,
    ) -> None:
        self.canned_comments = canned_comments
        self.default_confidence = default_confidence

    def generate_review(
        self,
        file_path: str,
        diff_hunk: str,
        context: str,
        language: str,
        convention_context: Optional[str] = None,
    ) -> List[CandidateComment]:
        if self.canned_comments is not None:
            return list(self.canned_comments)

        if not diff_hunk or not diff_hunk.strip():
            return []

        from action.diff_parser import parse_unified_diff

        # Prepend diff headers if missing to parse with unified diff parser
        diff_text = diff_hunk
        if "@@" not in diff_text:
            diff_text = f"@@ -0,0 +1,1 @@\n{diff_text}"
        if not diff_text.startswith("---") and not diff_text.startswith("diff --git"):
            diff_text = f"--- a/{file_path}\n+++ b/{file_path}\n{diff_text}"

        parsed_files = parse_unified_diff(diff_text)
        added_lines: List[tuple[int, str]] = []
        if parsed_files:
            for f in parsed_files:
                for hunk in f.hunks:
                    for line in hunk.lines:
                        if line.line_type == "+" and line.new_line_number is not None:
                            added_lines.append((line.new_line_number, line.content))

        if not added_lines:
            return []

        findings: List[CandidateComment] = []

        # Analyze added lines for mock patterns
        for lineno, content in added_lines:
            stripped = content.strip()
            if "eval(" in stripped or "exec(" in stripped:
                findings.append(
                    CandidateComment(
                        file_path=file_path,
                        line_number=lineno,
                        category="security",
                        severity="critical",
                        comment="Insecure dynamic code execution with eval/exec.",
                        suggestion=content.replace("eval(", "safe_eval(").replace("exec(", "safe_exec("),
                        confidence=0.95,
                        rule_id="sec-eval-exec",
                    )
                )
            elif "TODO" in stripped or "FIXME" in stripped:
                findings.append(
                    CandidateComment(
                        file_path=file_path,
                        line_number=lineno,
                        category="bug",
                        severity="minor",
                        comment="Unresolved TODO marker in committed code.",
                        suggestion=None,
                        confidence=0.75,
                        rule_id="todo-marker",
                    )
                )

        # Default fallback: if no specific mock pattern triggered, return a deterministic candidate on the first added line
        if not findings and added_lines:
            first_lineno, first_code = added_lines[0]
            findings.append(
                CandidateComment(
                    file_path=file_path,
                    line_number=first_lineno,
                    category="bug",
                    severity="major",
                    comment=f"Deterministic review check: verify potential edge case in '{first_code.strip()}'.",
                    suggestion=f"{first_code}  # checked",
                    confidence=self.default_confidence,
                    rule_id="mock-check",
                )
            )

        return findings


class OpenAICompatibleProvider(BaseReviewProvider):
    """
    Generic provider for OpenAI-compatible Chat Completions endpoints
    (Groq, OpenRouter, Ollama, OpenAI, Hugging Face).
    """

    def __init__(
        self,
        base_url: str,
        api_key: Optional[str] = None,
        model: str = "gpt-4o-mini",
        timeout: float = 10.0,
        extra_headers: Optional[Dict[str, str]] = None,
    ) -> None:
        self.base_url = base_url.rstrip("/")
        self.api_key = api_key or ""
        self.model = model
        self.timeout = timeout
        self.extra_headers = extra_headers or {}

    def _parse_response_json(self, response_text: str, file_path: str) -> List[CandidateComment]:
        """Safely parse JSON response from LLM into CandidateComment objects."""
        text = response_text.strip()

        # Strip markdown ```json code fence if present
        if "```" in text:
            fence_match = re.search(r"```(?:json)?\s*(\[.*?\])\s*```", text, re.DOTALL)
            if fence_match:
                text = fence_match.group(1).strip()
            else:
                # Try finding array bounds directly
                start = text.find("[")
                end = text.rfind("]")
                if start != -1 and end != -1 and end > start:
                    text = text[start : end + 1]

        try:
            data = json.loads(text)
        except Exception as e:
            logger.warning("Failed to parse LLM response JSON: %s. Raw: %s", e, text[:200])
            return []

        if not isinstance(data, list):
            return []

        candidates: List[CandidateComment] = []
        for item in data:
            if not isinstance(item, dict):
                continue
            line_no = item.get("line_number")
            if not isinstance(line_no, int):
                continue
            comment_text = str(item.get("comment", "")).strip()
            if not comment_text:
                continue

            candidates.append(
                CandidateComment(
                    file_path=file_path,
                    line_number=line_no,
                    category=str(item.get("category", "bug")),
                    severity=str(item.get("severity", "major")),
                    comment=comment_text,
                    suggestion=item.get("suggestion"),
                    confidence=float(item.get("confidence", 0.8)),
                    rule_id=item.get("rule_id", "ai-review"),
                )
            )

        return candidates

    def generate_review(
        self,
        file_path: str,
        diff_hunk: str,
        context: str,
        language: str,
        convention_context: Optional[str] = None,
    ) -> List[CandidateComment]:
        import urllib.request
        import urllib.error

        url = f"{self.base_url}/chat/completions"
        headers = {
            "Content-Type": "application/json",
            "Authorization": f"Bearer {self.api_key}",
            **self.extra_headers,
        }

        convention_block = (
            f"\n\n{convention_context.strip()}"
            if convention_context and convention_context.strip()
            else ""
        )
        # Enforce HARD-03b: Redact secrets before constructing LLM prompt
        clean_diff = redact_secrets(diff_hunk)
        clean_context = redact_secrets(context)

        user_content = (
            f"Review file: `{file_path}` (Language: {language})\n\n"
            f"DIFF HUNK:\n```diff\n{clean_diff}\n```\n\n"
            f"SURROUNDING CONTEXT:\n```{language}\n{clean_context}\n```"
            f"{convention_block}\n\n"
            "Return valid JSON array only."
        )

        payload = {
            "model": self.model,
            "messages": [
                {"role": "system", "content": SYSTEM_PROMPT},
                {"role": "user", "content": user_content},
            ],
            "temperature": 0.1,
        }

        req = urllib.request.Request(
            url,
            data=json.dumps(payload).encode("utf-8"),
            headers=headers,
            method="POST",
        )

        try:
            with urllib.request.urlopen(req, timeout=self.timeout) as resp:
                resp_data = json.loads(resp.read().decode("utf-8"))
                choices = resp_data.get("choices", [])
                if not choices:
                    return []
                message_content = choices[0].get("message", {}).get("content", "")
                return self._parse_response_json(message_content, file_path)
        except Exception as e:
            logger.warning("Provider request failed for %s: %s", url, e)
            return []


class GroqProvider(OpenAICompatibleProvider):
    """Groq ultra-fast BYOK provider."""

    def __init__(
        self,
        api_key: Optional[str] = None,
        model: Optional[str] = None,
        base_url: Optional[str] = None,
        **kwargs: Any,
    ) -> None:
        key = api_key or os.getenv("GROQ_API_KEY", "")
        url = base_url or "https://api.groq.com/openai/v1"
        mdl = model or "qwen-2.5-coder-32b"
        super().__init__(base_url=url, api_key=key, model=mdl, **kwargs)


