def get_provider(
    provider_type: str = "mock",
    api_key: Optional[str] = None,
    model: Optional[str] = None,
    base_url: Optional[str] = None,
    **kwargs: Any,
) -> BaseReviewProvider:
    """
    Factory function to instantiate configured review provider backend.

    Supported provider types: 'mock', 'groq', 'openrouter', 'ollama', 'openai', 'huggingface'.
    """
    p_type = provider_type.strip().lower()

    if p_type == "mock":
        return MockReviewProvider(**kwargs)
    elif p_type == "groq":
        return GroqProvider(api_key=api_key, model=model, base_url=base_url, **kwargs)
    elif p_type in ("openrouter", "open_router"):
        return OpenRouterProvider(api_key=api_key, model=model, base_url=base_url, **kwargs)
    elif p_type == "ollama":
        return OllamaProvider(api_key=api_key, model=model, base_url=base_url, **kwargs)
    elif p_type == "openai":
        return OpenAIProvider(api_key=api_key, model=model, base_url=base_url, **kwargs)
    elif p_type in ("huggingface", "hf"):
        return HuggingFaceProvider(api_key=api_key, model=model, base_url=base_url, **kwargs)
    else:
        raise ValueError(
            f"Unsupported provider_type '{provider_type}'. "
            "Supported: 'mock', 'groq', 'openrouter', 'ollama', 'openai', 'huggingface'."
        )
