"""
bench/schema.py

Strict Pydantic schemas for Aion-Bench evaluation suite (BENCH-01).
Covers benchmark test cases, ground-truth findings, reviewer comments,
case evaluations, and aggregate benchmark metrics.
"""

from __future__ import annotations

import json
from enum import Enum
from pathlib import Path
from typing import Any, Dict, List, Optional, Union
from pydantic import BaseModel, ConfigDict, Field


class FindingCategory(str, Enum):
    """Semantic category of code review findings."""
    BUG = "bug"                   # Logic errors, runtime crashes, exceptions
    SECURITY = "security"         # Injections, secret leaks, traversal, unsafe sinks
    PERFORMANCE = "performance"   # Algorithmic complexity, leaks, redundant operations
    STYLE = "style"               # Formatting, naming, conventions
    NITPICK = "nitpick"           # Trivial stylistic preferences, subjective commentary


class FindingSeverity(str, Enum):
    """Impact severity of code review findings."""
    CRITICAL = "critical"
    MAJOR = "major"
    MINOR = "minor"
    INFO = "info"


class SerializableModel(BaseModel):
    """Base model with ergonomic JSON/dict serialization helpers."""
    model_config = ConfigDict(populate_by_name=True, extra="ignore")

    def to_dict(self) -> Dict[str, Any]:
        """Convert model instance to standard Python dictionary."""
        return self.model_dump()

    def to_json(self, indent: Optional[int] = None) -> str:
        """Convert model instance to JSON string."""
        return self.model_dump_json(indent=indent)

    @classmethod
    def from_dict(cls, data: Dict[str, Any]):
        """Construct model instance from Python dictionary."""
        return cls.model_validate(data)

    @classmethod
    def from_json(cls, json_str: str):
        """Construct model instance from JSON string."""
        return cls.model_validate_json(json_str)


class GroundTruthFinding(SerializableModel):
    """
    Ground-truth finding anchored to exact line boundaries in a code file.
    """
    finding_id: str
    line_start: int
    line_end: int
    category: FindingCategory
    severity: FindingSeverity
    description: str
    file_path: Optional[str] = None
    fix_suggestion: Optional[str] = None
    rule_id: Optional[str] = None


class BenchmarkCase(SerializableModel):
    """
    Single self-contained benchmark case representing a code change / PR file diff.
    """
    case_id: str
    repository: str
    language: str                 # "python" | "typescript" | "javascript" etc.
    file_path: str
    original_code: str
    modified_code: str
    diff: str
    split: str                    # "dev" | "test_locked" | "gold"
    is_clean_diff: bool           # True if no real bugs exist (FPR measurement)
    ground_truth: List[GroundTruthFinding] = Field(default_factory=list)
    metadata: Dict[str, Any] = Field(default_factory=dict)


class ReviewComment(SerializableModel):
    """
    A single code review comment generated by an evaluation engine.
    """
    file_path: str
    line_number: int
    category: FindingCategory
    comment: str
    suggestion: Optional[str] = None
    confidence: float = 1.0


class CaseEvaluation(SerializableModel):
    """
    Scored evaluation of a reviewer engine's performance on a single BenchmarkCase.
    """
    case_id: str
    comments_posted: int
    true_positives: int
    false_positives: int
    false_negatives: int
    is_clean_diff: bool
    clean_diff_violation: bool   # True if comments were posted on a clean diff
    matched_findings: List[Dict[str, Any]] = Field(default_factory=list)
    duration_ms: float = 0.0
    nitpick_comments: int = 0


class BenchmarkMetrics(SerializableModel):
    """
    Aggregated benchmark performance metrics across a full split.
    """
    split: str
    total_cases: int
    clean_cases: int
    buggy_cases: int
    precision: float              # TP / (TP + FP)
    recall: float                 # TP / (TP + FN)
    false_positive_rate: float    # clean diffs with >=1 comment / total clean diffs
    avg_comments_per_pr: float    # total comments / total cases
    nitpick_rate: float           # nitpick comments / total comments
    avg_latency_ms: float         # mean duration_ms per case
    total_duration_sec: float     # wall-clock runtime in seconds


def load_cases_from_file(file_path: Union[str, Path]) -> List[BenchmarkCase]:
    """
    Load a list of BenchmarkCase instances from a JSON file.
    """
    path = Path(file_path)
    if not path.exists():
        raise FileNotFoundError(f"Benchmark cases file not found: {path}")

    with open(path, "r", encoding="utf-8") as f:
        data = json.load(f)

    if isinstance(data, list):
        return [BenchmarkCase.model_validate(item) for item in data]
    elif isinstance(data, dict) and "cases" in data:
        return [BenchmarkCase.model_validate(item) for item in data["cases"]]
    else:
        raise ValueError(f"Unrecognized benchmark cases JSON format in {path}")


def save_cases_to_file(cases: List[BenchmarkCase], file_path: Union[str, Path], indent: int = 2) -> None:
    """
    Save a list of BenchmarkCase instances to a JSON file.
    """
    path = Path(file_path)
    path.parent.mkdir(parents=True, exist_ok=True)

    data = [case.to_dict() for case in cases]
    with open(path, "w", encoding="utf-8") as f:
        json.dump(data, f, indent=indent, ensure_ascii=False)
